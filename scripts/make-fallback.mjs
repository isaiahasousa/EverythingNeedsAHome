// Builds src/generated/manifold-fallback.js: the manifold WASM module translated to plain JavaScript
// with binaryen's wasm2js. The app only loads it when a page's security policy refuses WebAssembly.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const wasm = path.resolve('node_modules/manifold-3d/manifold.wasm');
const outDir = path.resolve('src/generated');
const out = path.join(outDir, 'manifold-fallback.js');
const dts = path.join(outDir, 'manifold-fallback.d.ts');

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(dts, '/** Generated by scripts/make-fallback.mjs. */\nexport default function instantiate(imports: unknown): Record<string, unknown>;\n');
if (fs.existsSync(out) && fs.statSync(out).mtimeMs > fs.statSync(wasm).mtimeMs) {
  console.log('manifold-fallback.js is up to date');
  process.exit(0);
}
const tmp = out + '.tmp';
console.log('Translating manifold.wasm to JavaScript (about 15 s)...');
execFileSync(
  process.execPath,
  [
    path.resolve('node_modules/binaryen/bin/wasm2js'),
    wasm,
    '--emscripten',
    '-O2',
    '--enable-bulk-memory',
    '--enable-bulk-memory-opt',
    '--enable-sign-ext',
    '--enable-nontrapping-float-to-int',
    '--enable-mutable-globals',
    '-o',
    tmp,
  ],
  { stdio: 'inherit' },
);
const js = fs.readFileSync(tmp, 'utf8');
fs.writeFileSync(out, '/* eslint-disable */\n// Generated by scripts/make-fallback.mjs from manifold-3d (Apache-2.0). Do not edit.\n' + js + '\nexport default instantiate;\n');
fs.rmSync(tmp);
console.log(`wrote ${path.relative(process.cwd(), out)} (${(fs.statSync(out).size / 1e6).toFixed(1)} MB)`);
